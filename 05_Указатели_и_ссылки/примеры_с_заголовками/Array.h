#ifndef ARRAY_H
#define ARRAY_H

#include <iostream>

/*
 * ═══════════════════════════════════════════════════════════════
 * Заголовочный файл: Array.h
 * Уровень сложности: ★★★★☆ (Продвинутый)
 * ═══════════════════════════════════════════════════════════════
 *
 * ОПИСАНИЕ:
 * Демонстрирует создание класса динамического массива с полным
 * управлением памятью. Это пример того, как работают std::vector
 * и другие контейнеры STL "под капотом".
 *
 * ИЗУЧАЕМЫЕ КОНЦЕПЦИИ:
 * ✓ Управление динамической памятью (new/delete)
 * ✓ Конструктор копирования (глубокое копирование)
 * ✓ Оператор присваивания (правило трех)
 * ✓ Перегрузка операторов ([], <<)
 * ✓ Автоматическое увеличение размера
 * ✓ Инкапсуляция данных
 *
 * ЗАЧЕМ ЭТО НУЖНО:
 * - Понимание работы контейнеров STL
 * - Правильное управление ресурсами
 * - Избежание утечек памяти
 * - Создание собственных контейнеров
 *
 * ВАЖНО:
 * В реальных проектах используйте std::vector вместо
 * собственной реализации! Этот пример только для обучения.
 */

class Array {
private:
  // ═══ ПРИВАТНЫЕ ДАННЫЕ ═══
  int *data;    // Указатель на динамический массив данных
  int size;     // Текущее количество элементов
  int capacity; // Выделенная память (может быть больше size)

  // ═══ ПРИВАТНЫЕ МЕТОДЫ ═══
  // Увеличивает вместимость массива (обычно в 2 раза)
  // Вызывается автоматически при нехватке места
  void resize(int newCapacity);

public:
  // Конструкторы
  Array();                   // Конструктор по умолчанию
  Array(int initialSize);    // Конструктор с размером
  Array(const Array &other); // Конструктор копирования

  // Деструктор
  ~Array();

  // Оператор присваивания
  Array &operator=(const Array &other);

  // Доступ к элементам
  int &operator[](int index);             // Для изменения
  const int &operator[](int index) const; // Для чтения

  // Методы работы с массивом
  void push_back(int value);         // Добавить в конец
  void pop_back();                   // Удалить последний
  void insert(int index, int value); // Вставить по индексу
  void remove(int index);            // Удалить по индексу
  void clear();                      // Очистить массив

  // Геттеры
  int getSize() const;
  int getCapacity() const;
  bool isEmpty() const;

  // Поиск и сортировка
  int find(int value) const; // Найти элемент
  void sort();               // Сортировка
  void reverse();            // Реверс

  // Статистика
  int sum() const;        // Сумма элементов
  double average() const; // Среднее значение
  int min() const;        // Минимум
  int max() const;        // Максимум

  // Вывод
  void print() const;

  // Дружественная функция для вывода
  friend std::ostream &operator<<(std::ostream &os, const Array &arr);
};

#endif // ARRAY_H
