
/*
 * ═══════════════════════════════════════════════════════════════
 * Заголовочный файл: math.h
 * Уровень сложности: ★☆☆☆☆ (Начальный)
 * ═══════════════════════════════════════════════════════════════
 *
 * ОПИСАНИЕ:
 * Самый простой пример работы с заголовочными файлами.
 * Содержит объявления простых математических функций.
 *
 * ИЗУЧАЕМЫЕ КОНЦЕПЦИИ:
 * ✓ Что такое заголовочный файл (.h)
 * ✓ Зачем нужны include guards (#ifndef, #define, #endif)
 * ✓ Разница между объявлением и определением функции
 * ✓ Как компилировать несколько файлов вместе
 *
 * СТРУКТУРА ПРОЕКТА:
 * math.h         - Объявления функций (ЧТО делают функции)
 * math.cpp       - Определения функций (КАК они работают)
 * main.cpp       - Использование функций
 *
 * КОМПИЛЯЦИЯ:
 * g++ main.cpp math.cpp -o example1
 *
 * ЗАЧЕМ ЭТО НУЖНО:
 * - Разделение интерфейса и реализации
 * - Возможность использовать функции в разных файлах
 * - Упрощение больших проектов
 * - Ускорение компиляции (компилируем только измененные файлы)
 */

// ═══════════════════════════════════════════════════════════════
// INCLUDE GUARDS - Защита от повторного включения
// ═══════════════════════════════════════════════════════════════
// Эти три строки гарантируют, что файл будет включен только ОДИН раз,
// даже если его подключают в нескольких местах.
//
// Как это работает:
// 1. #ifndef MATH_H - "если MATH_H еще не определен"
// 2. #define MATH_H - "определить MATH_H"
// 3. ... код ...
// 4. #endif - "конец условия"
//
// При повторном включении MATH_H уже определен, поэтому код пропускается.
#ifndef MATH_H
#define MATH_H

// ═══════════════════════════════════════════════════════════════
// ОБЪЯВЛЕНИЯ ФУНКЦИЙ (Function Declarations)
// ═══════════════════════════════════════════════════════════════
// Здесь мы только ОБЪЯВЛЯЕМ функции (говорим компилятору, что они существуют).
// Само ОПРЕДЕЛЕНИЕ (код функции) находится в math.cpp
//
// Формат: тип_возврата имя_функции(параметры);

// Сложение двух чисел
// Параметры: a - первое число, b - второе число
// Возвращает: сумму a + b
// Пример: add(5, 3) вернет 8
int add(int a, int b);

// Вычитание двух чисел
// Параметры: a - уменьшаемое, b - вычитаемое
// Возвращает: разность a - b
// Пример: subtract(10, 3) вернет 7
int subtract(int a, int b);

// Умножение двух чисел
// Параметры: a - первый множитель, b - второй множитель
// Возвращает: произведение a * b
// Пример: multiply(4, 5) вернет 20
int multiply(int a, int b);

// Деление двух чисел
// Параметры: a - делимое, b - делитель
// Возвращает: частное a / b
// Пример: divide(10.0, 2.0) вернет 5.0
// ВАЖНО: Использует double для точного деления
double divide(double a, double b);

// Возведение в степень
// Параметры: base - основание, exponent - показатель степени
// Возвращает: base^exponent
// Пример: power(2, 3) вернет 8 (2*2*2)
int power(int base, int exponent);

// ═══════════════════════════════════════════════════════════════
// КОНЕЦ INCLUDE GUARDS
// ═══════════════════════════════════════════════════════════════
#endif // MATH_H

/*
 * ═══════════════════════════════════════════════════════════════
 * ВАЖНЫЕ ЗАМЕЧАНИЯ:
 * ═══════════════════════════════════════════════════════════════
 *
 * 1. ПОЧЕМУ ФУНКЦИИ РАЗДЕЛЕНЫ НА .h И .cpp?
 *    - .h файл - это "меню ресторана" (что доступно)
 *    - .cpp файл - это "кухня" (как это готовится)
 *    - Пользователю нужно знать только "меню", не "рецепты"
 *
 * 2. ЗАЧЕМ НУЖНЫ INCLUDE GUARDS?
 *    - Без них при повторном включении будут ошибки "redefinition"
 *    - Они защищают от случайного двойного включения
 *    - Это стандартная практика в C++
 *
 * 3. ЧТО ДАЛЬШЕ?
 *    - Посмотрите math.cpp - там определения этих функций
 *    - Посмотрите main.cpp - там примеры использования
 *    - Попробуйте добавить свою функцию!
 *
 * ═══════════════════════════════════════════════════════════════
 */