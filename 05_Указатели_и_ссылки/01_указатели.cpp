/*
 * Урок 1: Указатели
 * Тема: Основы работы с указателями и адресами памяти
 */

#include <iostream>
#include <windows.h>
using namespace std;

int main() {
    // Установка кодировки UTF-8 для корректного отображения русского текста
    SetConsoleOutputCP(CP_UTF8);
    SetConsoleCP(CP_UTF8);

    // Основы указателей
    cout << "=== ОСНОВЫ УКАЗАТЕЛЕЙ ===" << endl;
    int number = 42;
    int* pointer = &number;  // & - оператор взятия адреса
    
    cout << "Значение переменной: " << number << endl;
    cout << "Адрес переменной: " << &number << endl;
    cout << "Значение указателя (адрес): " << pointer << endl;
    cout << "Значение по указателю: " << *pointer << endl;  // * - разыменование
    
    // Изменение значения через pointer
    cout << "\n=== ИЗМЕНЕНИЕ ЧЕРЕЗ УКАЗАТЕЛЬ ===" << endl;
    *pointer = 100;
    cout << "Новое value переменной: " << number << endl;
    
    // Указатели и массивы
    cout << "\n=== УКАЗАТЕЛИ И МАССИВЫ ===" << endl;
    int array[] = {10, 20, 30, 40, 50};
    int* ptr = array;  // Имя массива - это pointer на first элемент
    
    cout << "Элементы массива через pointer:" << endl;
    for (int i = 0; i < 5; i++) {
        cout << "array[" << i << "] = " << *(ptr + i) << endl;
    }
    
    // Арифметика указателей
    cout << "\n=== АРИФМЕТИКА УКАЗАТЕЛЕЙ ===" << endl;
    int* p = array;
    cout << "Первый элемент: " << *p << endl;
    p++;  // Переход к следующему элементу
    cout << "Второй элемент: " << *p << endl;
    p += 2;  // Переход на 2 элемента вперед
    cout << "Четвертый элемент: " << *p << endl;
    
    // Нулевой pointer
    cout << "\n=== НУЛЕВОЙ УКАЗАТЕЛЬ ===" << endl;
    int* nullPtr = nullptr;
    if (nullPtr == nullptr) {
        cout << "Указатель не инициализирован" << endl;
    }
    
    return 0;
}

